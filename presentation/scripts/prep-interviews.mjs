#!/usr/bin/env node
// List the interview images the user dropped into public/interviews/ (jpg/png/webp) into src/interviews-manifest.json,
// so the "What students told us" chapter knows at build time whether it has anything real to show.
// No images and no data/interviews.json => the chapter is left out of the talk (never shown as "pending").
import { readdirSync, existsSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'public/interviews');
const images = existsSync(dir) ? readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort() : [];
const out = resolve(root, 'src/interviews-manifest.json');
const next = JSON.stringify({ _doc: 'generated by scripts/prep-interviews.mjs — do not edit', images }, null, 2) + '\n';
if (!existsSync(out) || readFileSync(out, 'utf8') !== next) writeFileSync(out, next);
console.log(`prep-interviews: ${images.length} image(s); data/interviews.json ${existsSync(resolve(root, 'data/interviews.json')) ? 'present' : 'absent'}`);
